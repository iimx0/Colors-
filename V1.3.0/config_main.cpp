void reload_config() {
    std::string config_path = get_or_init_config_path();
    
    if (!config_path.empty()) {
        load_config_internal(config_path);
    }
}

std::vector<std::string> get_all_users() {
    std::string config_path = get_or_init_config_path();
    
    if (config_path.empty()) {
        return {};
    }
    
    if (!is_cache_valid(config_path)) {
        if (!load_config_internal(config_path)) {
            return {};
        }
    }
    
    return get_cached_users();
}

bool has_user_config(const std::string& username) {
    std::string config_path = get_or_init_config_path();
    
    if (config_path.empty()) {
        return false;
    }
    
    if (!is_cache_valid(config_path)) {
        if (!load_config_internal(config_path)) {
            return false;
        }
    }
    
    return has_config_in_cache(username);
}